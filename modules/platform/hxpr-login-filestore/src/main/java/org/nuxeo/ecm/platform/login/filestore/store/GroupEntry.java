package org.nuxeo.ecm.platform.login.filestore.store;

/**
 * Represents a group entry loaded from the YAML user-store file.
 */
public class GroupEntry {

    private String id;

    private String name;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
