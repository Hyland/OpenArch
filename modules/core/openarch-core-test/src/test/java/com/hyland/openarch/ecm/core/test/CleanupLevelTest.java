package com.hyland.openarch.ecm.core.test;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static com.hyland.openarch.ecm.core.api.DocumentConstants.SYS_TITLE;
import static com.hyland.openarch.ecm.core.schema.TypeConstants.SYS_FOLDER;

import jakarta.inject.Inject;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import com.hyland.openarch.ecm.core.api.CoreSession;
import com.hyland.openarch.ecm.core.api.DocumentModel;
import com.hyland.openarch.ecm.core.api.PathRef;
import com.hyland.openarch.ecm.core.test.annotations.Granularity;
import com.hyland.openarch.ecm.core.test.annotations.RepositoryConfig;
import com.hyland.openarch.runtime.test.runner.Features;
import com.hyland.openarch.runtime.test.runner.FeaturesExtension;

@ExtendWith(FeaturesExtension.class)
@RepositoryConfig(cleanup = Granularity.METHOD)
@Features(CoreFeature.class)
public class CleanupLevelTest {

    @Inject
    CoreSession session;

    @Test
    public void firstTestToCreateADoc() throws Exception {
        DocumentModel doc = session.createDocumentModel("/", "test", SYS_FOLDER);
        doc.setPropertyValue(SYS_TITLE, "test");
        doc.create();
        session.save();
        assertTrue(session.exists(new PathRef("/test")));
    }

    @Test
    public void docDoesNotExistsNoMore() throws Exception {
        assertFalse(session.exists(new PathRef("/test")));
    }

}
